// Optional native proof. GAPCUE_SKILL points to a separate, unmodified installation.
import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync, writeFileSync, readFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join, resolve} from 'node:path';
import {spawn, spawnSync} from 'node:child_process';
import {createRequire} from 'node:module';
import {pathToFileURL} from 'node:url';
import {consumerRoots} from '../scripts/lib/consumer-paths.mjs';
import {captureRequirements, prepareRequirements, startRequirementsReview, resumeRequirementsReview, importDecisions, readReviewHandoff} from '../scripts/lib/requirements/index.mjs';
import {resolveGapCue} from '../scripts/lib/requirements/gapcue.mjs';

test('unmodified GapCue UI edits, native export and fresh-session recovery', {timeout: 60000}, async t => {
  assert(process.env.GAPCUE_SKILL, 'Set GAPCUE_SKILL to the separately installed pinned GapCue skill directory.');
  const skill = resolve(process.env.GAPCUE_SKILL), root = mkdtempSync(join(tmpdir(), 'gapcue-native-'));
  const require = createRequire(new URL('../examples/package.json', import.meta.url));
  const {chromium} = require('playwright');
  const roots = consumerRoots(root), sourcePath = join(root, 'requirements.md');
  writeFileSync(sourcePath, 'Names allow spaces & special characters.\nResponse time is unspecified.\n');
  const request = {version: 1, project: 'synthetic-shop', application: 'checkout', sources: [{id: 'notes', kind: 'file', path: 'requirements.md'}]};
  const prepared = prepareRequirements(roots, 'checkout', await captureRequirements(roots, request));
  const findings = [{id: 'latency', kind: 'gap', title: 'Response-time target', why: 'A measurable target is missing.', q: 'What response time is required?', anchors: [{text: 'Response time is unspecified.'}], requirementIds: [prepared.inventory[1].id]}];
  const review = startRequirementsReview(roots, 'checkout', {gapcue: skill, findings}), story = {id: review.review.storyId};
  const nativeRoot = join(root, review.review.root);
  const child = spawn(process.execPath, [join(skill, 'scripts/review.mjs'), '--serve', '--root', nativeRoot, '--port', '0', '--no-open'], {env: {...process.env, GAPCUE_NO_UPDATE_CHECK: '1'}, windowsHide: true});
  t.after(() => child.kill());
  const url = await new Promise((accept, reject) => {
    let output = ''; const timer = setTimeout(() => reject(new Error('GapCue did not start: ' + output)), 15000);
    child.stdout.on('data', bytes => {output += bytes; const value = /history:\s+(http:\/\/127\.0\.0\.1:\d+\/)/.exec(output)?.[1]; if (value) {clearTimeout(timer); accept(value + story.id + '/v1/index.html');}});
    child.stderr.on('data', bytes => {output += bytes;});
    child.once('exit', code => {clearTimeout(timer); reject(new Error(`GapCue exited ${code}: ${output}`));});
  });
  const browser = await chromium.launch({headless: true}); t.after(() => browser.close());
  let context = await browser.newContext({acceptDownloads: true}), page = await context.newPage();
  await page.goto(url);
  await page.locator('[data-g="latency"]').first().click();
  await page.locator('#qEdit').click();
  await page.locator('#qText').fill('What is the accepted p95 response-time target?');
  await page.locator('#qSave').click();
  await page.locator('#bApprove').click();
  await page.locator('#popClose').click();
  // Select actual rendered source text, then use GapCue's native custom-finding UI.
  await page.locator('#sections p').filter({hasText: 'Names allow'}).evaluate(element => {
    const range = document.createRange(); range.selectNodeContents(element);
    const selection = window.getSelection(); selection.removeAllRanges(); selection.addRange(range);
    element.dispatchEvent(new MouseEvent('mouseup', {bubbles: true}));
  });
  await page.locator('#selbar').getByRole('button', {name: /Gap/}).click();
  await page.locator('#nfQ').fill('Which display-name examples should the team retain?');
  await page.locator('#nfSave').click();
  await page.locator('#popClose').click();
  await page.locator('#cEdit').click();
  await page.locator('#cText').fill('Manual final comment: please confirm the response target.');
  const downloadEvent = page.waitForEvent('download'); await page.locator('#cExport').click();
  const download = await downloadEvent, exported = join(root, 'decisions.json'); await download.saveAs(exported);
  const decisions = JSON.parse(readFileSync(exported));
  assert.equal(decisions.gapcue, 1); assert.equal(decisions.schema, 2); assert.equal(decisions.story, story.id);
  assert.match(decisions.qEdit.latency, /accepted p95/); assert.equal(decisions.custom.length, 1);
  assert.match(decisions.comment, /Manual final comment/); assert.equal(decisions.dirty, true);
  await page.waitForFunction(() => document.querySelector('#saveState')?.textContent?.includes('disk') || document.body.textContent.includes('Saved to disk'));
  const disk = JSON.parse(readFileSync(join(nativeRoot, story.id, 'v1/state.json')));
  assert.equal(disk.comment, decisions.comment); assert.deepEqual(disk.custom, decisions.custom);
  await context.close();
  context = await browser.newContext(); page = await context.newPage(); await page.goto(url);
  assert.match(await page.locator('#cText').textContent(), /Manual final comment/);
  await Promise.all([page.waitForEvent('load'), page.locator('#cFile').setInputFiles(exported)]);
  const imported = importDecisions(roots, 'checkout', 'decisions.json'); assert.equal(readReviewHandoff(roots, imported).comment, decisions.comment);
  assert.equal(resumeRequirementsReview(roots, 'checkout', {gapcue: skill}).analysisInvocations, 1);
  assert.throws(() => resumeRequirementsReview(roots, 'checkout', {gapcue: join(root, 'unsupported-upgrade')}), /incompatible/);
  assert.equal(resumeRequirementsReview(roots, 'checkout', {gapcue: skill}).review.handoff.sha256, imported.review.handoff.sha256);
  const recovered = spawnSync(process.execPath, ['-e', 'const fs=require("node:fs");process.stdout.write(fs.readFileSync(process.argv[1],"utf8"))', join(nativeRoot, story.id, 'v1/state.json')], {encoding: 'utf8', windowsHide: true});
  assert.equal(recovered.status, 0); assert.match(JSON.parse(recovered.stdout).qEdit.latency, /accepted p95/);
  const standalone = join(root, 'browser-only');
  const builtSingle = spawnSync(process.execPath, [join(skill, 'scripts/review.mjs'), join(root, review.review.input), '--single-file', '--out', standalone], {encoding: 'utf8', env: {...process.env, GAPCUE_NO_UPDATE_CHECK: '1'}, windowsHide: true});
  assert.equal(builtSingle.status, 0, builtSingle.stderr);
  const browserOnly = await browser.newContext({acceptDownloads: true}), filePage = await browserOnly.newPage();
  await filePage.goto(pathToFileURL(join(standalone, story.id + '-review.html')).href);
  await Promise.all([filePage.waitForEvent('load'), filePage.locator('#cFile').setInputFiles(exported)]);
  assert.equal(await filePage.locator('#sOwn').textContent(), '1');
  await filePage.locator('#cEdit').click(); await filePage.locator('#cText').fill('Browser-only manually preserved final comment.');
  const fileDownloadEvent = filePage.waitForEvent('download'); await filePage.locator('#cExport').click();
  await (await fileDownloadEvent).saveAs(join(root, 'browser-only.json'));
  assert.equal(JSON.parse(readFileSync(join(nativeRoot, story.id, 'v1/state.json'))).comment, decisions.comment);
  const browserImported = importDecisions(roots, 'checkout', 'browser-only.json'), finalComment = readReviewHandoff(roots, browserImported).comment;
  assert.match(finalComment, /Browser-only manually/);
  await filePage.screenshot({path: join(root, 'browser-only-proof.png'), fullPage: true});
  // A changed source gets a new identity/root, never ID-only automatic carry.
  writeFileSync(sourcePath, 'Names allow spaces & special characters.\nResponse time is below 2 seconds.\n');
  const updated = prepareRequirements(roots, 'checkout', await captureRequirements(roots, request));
  assert.equal(readReviewHandoff(roots, updated, updated.priorReviews[0]).comment, finalComment);
  const changed = startRequirementsReview(roots, 'checkout', {gapcue: skill, findings: []});
  assert.deepEqual(JSON.parse(readFileSync(join(root, changed.review.root, changed.review.storyId, 'v1/state.json'))).status, {});
  assert.equal(resolveGapCue(skill).content, review.review.dependency.content);
  assert.equal(JSON.parse(readFileSync(exported)).comment, decisions.comment);
  t.diagnostic(JSON.stringify({root, url, dependencyVersion: '0.3.0', sourceChanged: true, nativeExport: exported, browser: await browser.version()}));
});
